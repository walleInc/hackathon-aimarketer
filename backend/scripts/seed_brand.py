ASSETS = [
    ("logo_color", "logos/logo_color.png"), ("logo_white", "logos/logo_white.png"), ("logo_black", "logos/logo_black.png"),
    ("icon", "logos/icon_color.png"), ("pattern", "patterns/pattern_1.png"), ("pattern", "patterns/pattern_2.png"),
    ("pattern", "patterns/pattern_3.png"), ("font_heading", "fonts/Intro.ttf"), ("font_body", "fonts/avenirnextcyr-regular.ttf"),
]


async def main(channel: str) -> None:
    await init_db()
    async with SessionLocal() as s:
        c = Company(
            name="САЛАВАТСТЕКЛО",
            description="Группа компаний — производитель листового стекла, один из крупнейших в России.",
            brand_style="Деловой, спокойный и благородный тон. Короткие абзацы, факты вместо эпитетов.",
            brand_rules=RULES,
            brand_colors="#196C7F, #285055, #C1D0D3, #DDE1E1, #8ACCD9, #0094A8, #289389, #E5917F, #DB6051, #D33835",
        )
        s.add(c)
        await s.commit()
        for kind, rel in ASSETS:
            src = PACK / rel
            dst, url = new_media_file(f"brand/{c.id}", src.suffix)
            shutil.copyfile(src, dst)
            s.add(BrandAsset(company_id=c.id, kind=kind, filename=src.name, path=url))
        s.add_all([KnowledgeDoc(company_id=c.id, title=t, content=body) for t, body in KNOWLEDGE.items()])
        s.add(SocialAccount(company_id=c.id, platform="telegram", channel_id=channel))
        code = secrets.token_urlsafe(12)
        s.add(Invite(code=code, company_id=c.id, role="approver"))
        await s.commit()
        print(f"company_id={c.id}\ninvite=https://t.me/aimarketologgbot?start={code}")


asyncio.run(main(sys.argv[1]))
